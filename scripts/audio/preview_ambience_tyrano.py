def loop_file(name: str) -> str:
    return f"{name}.flac"


def make_loops() -> None:
    import soundfile

    from scripts.audio.probe_ambience_loops import equal_power_loop

    results = json.loads((LOOPS / "results.json").read_text("utf-8"))
    folder = OUTPUT / "ambience"
    folder.mkdir(parents=True, exist_ok=True)
    for name, spec in ASSETS.items():
        row = next(value for value in results[name] if value["take"] == spec["take"])
        audio, rate = soundfile.read(LOOPS / f"sources/{name}_{spec['take']}.flac", dtype="float32", always_2d=True)
        start, end, fade = (round(row[key] * rate) for key in ("start", "end", "fade"))
        soundfile.write(folder / loop_file(name), equal_power_loop(audio, start, end, fade), rate, subtype="PCM_16")
        print(name, f"take {spec['take']}", f"{(end - start) / rate:.1f}s", flush=True)


def export_zip(connection: sqlite3.Connection, build_id: str) -> Path:
    row = connection.execute(
        "SELECT a.storage_key FROM chapter_build b JOIN artifact a ON a.id = b.export_artifact_id "
        "WHERE b.id = ? AND b.status = 'published'", (build_id,)).fetchone()
    if row is None:
        raise SystemExit(f"published build not found: {build_id}")
    return ROOT / "data/artifacts" / row[0]


def unpack(path: Path, folder: Path) -> dict[str, bytes]:
    """The ZIP's members, with the viewing screen regenerated by the current code (as /player/ serves it)."""
    from packages.contracts import Script
    from packages.tyrano_export.compiler import ASSET_FOLDERS, player_overlay

    with zipfile.ZipFile(path) as archive:
        files = {name: archive.read(name) for name in archive.namelist()}
    script = Script.model_validate(json.loads(files["script.json"]))
    images = {asset.id: files[f"data/{ASSET_FOLDERS[asset.kind]}/{asset.filename}"]
              for asset in script.assets if asset.kind in {"background", "character"}}
    files.update(player_overlay(script, images, files["script.json"]))
    for name, content in files.items():
        target = folder / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    return files


def check_spans(chapter: dict, script: dict) -> None:
    lines = {line["id"] for line in script["utterances"]}
    for span in chapter["spans"]:
        for edge in (span["from"], span["until"]):
            if edge is not None and edge not in lines:
                raise SystemExit(f"{chapter['slug']}: line {edge} is not in the published chapter")


def build() -> None:
    connection = sqlite3.connect(ROOT / "data/auto_drama.db")
    try:
        zips = {chapter["slug"]: export_zip(connection, chapter["build"]) for chapter in CHAPTERS}
    finally:
        connection.close()
    for chapter in CHAPTERS:
        folder = OUTPUT / chapter["slug"]
        if folder.exists():
            shutil.rmtree(folder)
        files = unpack(zips[chapter["slug"]], folder)
        check_spans(chapter, json.loads(files["script.json"]))
        used = {span["asset"] for span in chapter["spans"]}
        (folder / "ambience").mkdir()
        for name in used:
            shutil.copyfile(OUTPUT / "ambience" / loop_file(name), folder / "ambience" / loop_file(name))
        spans = [{**span, "gain": ASSETS[span["asset"]]["gain"]} for span in chapter["spans"]]
        assets = {name: {"file": loop_file(name), "label": ASSETS[name]["label"]} for name in used}
        (folder / "ambience.json").write_text(json.dumps({"spans": spans, "assets": assets}, ensure_ascii=False,
                                                         indent=1), "utf-8")
        shutil.copyfile(Path(__file__).with_name("preview_ambience.js"), folder / "preview_ambience.js")
        page = (folder / "index.html").read_text("utf-8")
        if "</head>" not in page:
            raise SystemExit(f"{chapter['slug']}: no </head> in index.html")
        page = page.replace("</head>", '<script defer src="./preview_ambience.js"></script></head>', 1)
        (folder / "index.html").write_text(page, "utf-8")
        print(chapter["slug"], len(spans), "spans", flush=True)
    rows = "".join(
        f'<li><a href="./{chapter["slug"]}/">{chapter["title"]}</a>（環境音の区間 {len(chapter["spans"])}）</li>'
        for chapter in CHAPTERS)
    (OUTPUT / "index.html").write_text(
        "<!doctype html><meta charset=utf-8><title>環境音の試聴</title>"
        "<style>body{font-family:sans-serif;margin:24px;line-height:1.8}</style>"
        f"<h1>環境音を足した章</h1><ul>{rows}</ul>"
        "<p>画面右上の切り替えで、オフ／そのまま／位置で処理 を比べられます。</p>", "utf-8")


class Handler(http.server.SimpleHTTPRequestHandler):
    """The preview folder, with every chapter's tyrano/ served from the installed engine."""

    def translate_path(self, path):
        parts = path.split("?", 1)[0].split("#", 1)[0].lstrip("/").split("/")
        if len(parts) > 2 and parts[1] == "tyrano":
            engine = (ROOT / "tyranoscript").resolve()
            target = (engine / "/".join(parts[1:])).resolve()
            if target.is_relative_to(engine / "tyrano"):
                return str(target)
        return super().translate_path(path)

    def end_headers(self):
        self.send_header("Cache-Control", "no-store")
        super().end_headers()


def serve(port: int) -> None:
    server = http.server.ThreadingHTTPServer(("127.0.0.1", port), partial(Handler, directory=str(OUTPUT)))
    print(f"http://127.0.0.1:{port}/", flush=True)
    server.serve_forever()


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=("loops", "build", "serve"))
    parser.add_argument("--port", type=int, default=8765)
    args = parser.parse_args()
    if args.command == "loops":
        make_loops()
    elif args.command == "build":
        build()
    else:
        serve(args.port)
    return 0


